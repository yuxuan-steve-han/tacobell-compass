def encode(ch, art):
    rows = art.split()
    if len(rows) != HEIGHT or len({len(r) for r in rows}) != 1 or len(rows[0]) > 8:
        raise ValueError(f'glyph {ch!r} must be {HEIGHT} equal rows of at most 8 columns')
    return len(rows[0]), [sum(1 << (7 - i) for i, p in enumerate(r) if p == '#') for r in rows]


def main(out):
    lines = ['// Generated by tools/make_font.py: chunky 7px-tall pixel font, uppercase + digits.',
             '#pragma once', '#include <stdint.h>', '',
             f'#define PF_HEIGHT {HEIGHT}', f'#define PF_FIRST {FIRST}', f'#define PF_LAST {LAST}', '',
             '// Per glyph: width, then 7 rows (MSB = leftmost column). Width 0 = not defined.',
             f'static const uint8_t PF_GLYPHS[PF_LAST - PF_FIRST + 1][{HEIGHT + 1}] = {{']
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        if ch not in GLYPHS:
            lines.append(f'  {{0}},{" " * 38}// {ch!r}')
            continue
        w, rows = encode(ch, GLYPHS[ch])
        lines.append(f'  {{{w}, ' + ', '.join(f'0x{b:02X}' for b in rows) + f'}}, // {ch!r}')
    lines.append('};')
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print(f'{out}: {len(GLYPHS)} glyphs')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
